def _fig_to_png_bytes(fig: Figure, dpi: int = 190) -> bytes:
    canvas = FigureCanvasAgg(fig)
    buf = io.BytesIO()
    canvas.print_figure(buf, format="png", dpi=dpi, facecolor=fig.get_facecolor())
    return buf.getvalue()


def _make_cover_figure(
    title: str,
    subtitle: str,
    kpi_rows: list[tuple[str, str, str]],
) -> Figure:
    fig = Figure(figsize=(11.0, 6.2), facecolor="#0F172A")
    ax = fig.add_axes([0.04, 0.05, 0.92, 0.90], facecolor="#0F172A")
    ax.axis("off")

    ax.text(0.0, 0.93, title, fontsize=20, fontweight="bold", color="#F8FAFC")
    ax.text(0.0, 0.86, subtitle, fontsize=11.5, color="#93C5FD")
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    ax.text(0.0, 0.80, f"Generated by ammo-mc v{__version__} | {stamp}", fontsize=9.5, color="#94A3B8")

    # Governance banner
    ax.text(
        0.0,
        0.70,
        f"GOVERNANCE NOTICE: {USE_LIMITATION_NOTICE}",
        fontsize=9.0,
        color="#FDE68A",
        bbox=dict(boxstyle="round,pad=0.5", facecolor="#451A03", edgecolor="#F59E0B", linewidth=1.2),
        wrap=True,
    )

    if kpi_rows:
        table = ax.table(
            cellText=[[a, b, c] for a, b, c in kpi_rows[:12]],
            colLabels=["Domain / Subsystem", "Key Engineering Metric", "Result"],
            loc="center",
            bbox=[0.0, 0.05, 1.0, 0.56],
        )
        table.auto_set_font_size(False)
        table.set_fontsize(9.5)
        for (row_idx, _col_idx), cell in table.get_celld().items():
            if row_idx == 0:
                cell.set_facecolor("#1E3A8A")
                cell.set_text_props(color="#FFFFFF", fontweight="bold")
            else:
                cell.set_facecolor("#1E293B" if row_idx % 2 == 1 else "#0F172A")
                cell.set_text_props(color="#E2E8F0")
            cell.set_edgecolor("#334155")
    return fig


def _make_ab_radar_chart_fig(ab_res: dict[str, Any]) -> Figure:
    fig = Figure(figsize=(11.0, 6.2), facecolor="#0F172A")
    rows = ab_res.get("scorecard", ab_res.get("candidates", []))
    sm_ab = ab_res.get("summary", {})
    radar_keys = [
        "Kill-Chain Pk",
        "Swarm Endurance",
        "Recoil Stability",
        "SDZ Compactness",
        "Thermal Margin",
        "Cost Efficiency",
    ]
    n_ax = len(radar_keys)
    angles = np.linspace(0, 2 * np.pi, n_ax, endpoint=False).tolist()
    angles += angles[:1]

    ax_pol = fig.add_subplot(1, 2, 1, projection="polar", facecolor="#1E293B")
    palette = ["#38BDF8", "#10B981", "#F59E0B", "#EC4899"]
    for idx, c in enumerate(rows[:4]):
        rs_dict = c.get("radar_scores", c.get("normalized_scores", {}))
        vals = [float(rs_dict.get(k, 50.0)) for k in radar_keys]
        vals += vals[:1]
        col = palette[idx % len(palette)]
        lbl = str(c.get("short_name", c.get("name", f"Cand {idx+1}")))[:26]
        ax_pol.plot(angles, vals, color=col, linewidth=2.2, label=lbl)
        ax_pol.fill(angles, vals, color=col, alpha=0.14)

    ax_pol.set_xticks(angles[:-1])
    ax_pol.set_xticklabels([k.replace(" ", "\n") for k in radar_keys], color="#E2E8F0", fontsize=8.5)
    ax_pol.set_ylim(0, 100)
    ax_pol.tick_params(colors="#94A3B8")
    ax_pol.grid(color="#475569", alpha=0.6)
    ax_pol.set_title("A/B Multi-Criteria Radar Scorecard", color="#F8FAFC", pad=16, fontsize=11.5, fontweight="bold")
    ax_pol.legend(loc="upper center", bbox_to_anchor=(0.5, -0.10), frameon=False, labelcolor="#E2E8F0", fontsize=8)

    ax_bar = fig.add_subplot(1, 2, 2, facecolor="#1E293B")
    names = [str(c.get("short_name", c.get("label", c.get("name", ""))))[:26] for c in rows]
    scores = [float(c.get("mei_score", c.get("composite_score", 0.0))) for c in rows]
    y_pos = np.arange(len(names))
    ax_bar.barh(y_pos, scores, color=[palette[i % len(palette)] for i in range(len(names))], height=0.55)
    ax_bar.set_yticks(y_pos)
    ax_bar.set_yticklabels(names, color="#E2E8F0", fontsize=8.5)
    ax_bar.invert_yaxis()
    ax_bar.set_xlim(0, 110)
    ax_bar.set_xlabel("Composite Mission Score MEI (0-100)", color="#CBD5E1")
    ax_bar.tick_params(colors="#CBD5E1")
    win_name = str(sm_ab.get("winner_label", ab_res.get("winner_name", "")))[:38]
    ax_bar.set_title(f"Winner: {win_name}", color="#10B981", fontsize=11, fontweight="bold")
    for i, sc in enumerate(scores):
        ax_bar.text(sc + 1.5, i, f"{sc:.1f}", va="center", color="#F8FAFC", fontsize=9)
    fig.tight_layout(pad=2.0)
    return fig


def _make_site_or_raid_chart_fig(site_res: dict[str, Any] | None, raid_res: dict[str, Any] | None) -> Figure:
    fig = Figure(figsize=(11.0, 6.2), facecolor="#0F172A")
    src = raid_res if raid_res is not None else site_res
    assert src is not None
    turrets = src.get("turrets", [])
    obstacles = src.get("obstacles", [])
    nfzs = src.get("nfz_zones", [])
    sm = src.get("summary", {})
    asset_r = float(sm.get("asset_radius_m", 40.0))

    ax = fig.add_subplot(1, 2, 1, facecolor="#1E293B")
    th = np.linspace(0.0, 2.0 * np.pi, 100)
    ax.plot(asset_r * np.cos(th), asset_r * np.sin(th), "--", color="#3B82F6", linewidth=1.8, label="Perimeter")
    for o in obstacles:
        ox, oy = float(o["x_m"]), float(o["y_m"])
        hw, hl = 0.5 * float(o["width_m"]), 0.5 * float(o["length_m"])
        ax.fill([ox - hw, ox + hw, ox + hw, ox - hw], [oy - hl, oy - hl, oy + hl, oy + hl], color="#64748B", alpha=0.65)
    for n in nfzs:
        nx, ny, nr = float(n["x_m"]), float(n["y_m"]), float(n["radius_m"])
        ax.fill(nx + nr * np.cos(th), ny + nr * np.sin(th), color="#EF4444", alpha=0.22)
    for t in turrets:
        ax.scatter([float(t["x_m"])], [float(t["y_m"])], marker="D", s=65, color="#38BDF8", zorder=5)
        ax.text(float(t["x_m"]) + 2.0, float(t["y_m"]) + 2.0, t["id"], color="#E2E8F0", fontsize=8)
    ax.set_aspect("equal", "box")
    ax.set_xlabel("East X (m)", color="#CBD5E1")
    ax.set_ylabel("North Y (m)", color="#CBD5E1")
    ax.tick_params(colors="#CBD5E1")
    ax.set_title("Defended Site Layout, Buildings & NFZs", color="#F8FAFC", fontsize=11, fontweight="bold")
    ax.grid(color="#334155", alpha=0.5)

    ax2 = fig.add_subplot(1, 2, 2, facecolor="#1E293B")
    if raid_res is not None and raid_res.get("timeline_series"):
        ts = raid_res["timeline_series"]
        tv = [r["t_s"] for r in ts]
        ax2.plot(tv, [r["kills_cum"] for r in ts], color="#10B981", linewidth=2.2, label="Kills (Cum)")
        ax2.plot(tv, [r["breaches_cum"] for r in ts], color="#EF4444", linewidth=2.0, label="Breaches (Cum)")
        ax2.plot(tv, [r["active_threats"] for r in ts], color="#38BDF8", linewidth=1.8, linestyle="--", label="Inbound Active")
        ax2.set_xlabel("Raid Clock (s)", color="#CBD5E1")
        ax2.set_ylabel("Drone Count", color="#CBD5E1")
        ax2.set_title(
            f"Unified Raid Attrition ({sm.get('mean_kill_rate_pct', 0.0):.1f}% Kill Rate)",
            color="#F8FAFC",
            fontsize=11,
            fontweight="bold",
        )
        ax2.legend(facecolor="#0F172A", labelcolor="#E2E8F0", fontsize=8.5)
    elif site_res is not None and site_res.get("azimuth_profile"):
        prof = site_res["azimuth_profile"]
        azs = [r["az_deg"] for r in prof]
        cnts = [r["active_turrets"] for r in prof]
        cols = ["#EF4444" if c == 0 else ("#F59E0B" if c == 1 else "#10B981") for c in cnts]
        ax2.bar(azs, cnts, width=4.5, color=cols)
        ax2.set_xlabel("Azimuth (°)", color="#CBD5E1")
        ax2.set_ylabel("Active Unobstructed Turrets", color="#CBD5E1")
        ax2.set_title(
            f"360° Azimuth Coverage ({sm.get('perimeter_coverage_pct', 0.0):.1f}%)",
            color="#F8FAFC",
            fontsize=11,
            fontweight="bold",
        )
    ax2.tick_params(colors="#CBD5E1")
    ax2.grid(color="#334155", alpha=0.4)
    fig.tight_layout(pad=2.0)
    return fig


def _make_tornado_chart_fig(tornado_res: dict[str, Any]) -> Figure:
    fig = Figure(figsize=(11.0, 6.2), facecolor="#0F172A")
    ax = fig.add_subplot(1, 1, 1, facecolor="#1E293B")
    rows = tornado_res.get("rows", [])[:10]
    sm = tornado_res.get("summary", {})
    base = float(sm.get("baseline_value", 0.0))

    labels = [r.get("label", "") for r in rows]
    y_pos = np.arange(len(labels))
    low_d = [
        float(r["delta_low"]) if "delta_low" in r else (float(r.get("val_at_low", r.get("low_value", base))) - base)
        for r in rows
    ]
    high_d = [
        float(r["delta_high"]) if "delta_high" in r else (float(r.get("val_at_high", r.get("high_value", base))) - base)
        for r in rows
    ]

    ax.barh(y_pos, low_d, color="#38BDF8", height=0.55, label=f"-{sm.get('perturbation_pct', 20):.0f}% Parameter")
    ax.barh(y_pos, high_d, color="#F59E0B", height=0.55, label=f"+{sm.get('perturbation_pct', 20):.0f}% Parameter")
    ax.axvline(0.0, color="#F8FAFC", linewidth=1.2)
    ax.set_yticks(y_pos)
    ax.set_yticklabels(labels, color="#E2E8F0", fontsize=9)
    ax.invert_yaxis()
    ax.set_xlabel(f"Delta from Baseline ({base:.2f})", color="#CBD5E1")
    ax.tick_params(colors="#CBD5E1")
    ax.set_title(
        f"OAT Sensitivity & Bottleneck Tornado (#1: {sm.get('top_driver', '')})",
        color="#F8FAFC",
        fontsize=12,
        fontweight="bold",
    )
    ax.legend(facecolor="#0F172A", labelcolor="#E2E8F0")
    ax.grid(axis="x", color="#334155", alpha=0.5)
    fig.tight_layout(pad=2.0)
    return fig


def _make_logistics_chart_fig(log_res: dict[str, Any]) -> Figure:
    fig = Figure(figsize=(11.0, 6.2), facecolor="#0F172A")
    econ = log_res.get("economics_comparison", [])
    sm = log_res.get("summary", {})

    ax = fig.add_subplot(1, 1, 1, facecolor="#1E293B")
    names = [str(r.get("ammo_family", "")).split("(")[0].strip() for r in econ]
    cpks = [float(r.get("cost_per_kill_usd", 0.0)) for r in econ]
    cols = ["#10B981" if c < 10.0 else ("#F59E0B" if c < 40.0 else "#EF4444") for c in cpks]
    x_pos = np.arange(len(names))
    ax.bar(x_pos, cpks, color=cols, width=0.58)
    ax.set_xticks(x_pos)
    ax.set_xticklabels(names, rotation=20, ha="right", color="#E2E8F0", fontsize=8.5)
    ax.set_ylabel("Cost per Neutralized Drone ($/Kill)", color="#CBD5E1")
    ax.tick_params(colors="#CBD5E1")
    ax.set_title(
        f"Sustained Logistics & Payload Economics | Peak Barrel Temp: {sm.get('peak_barrel_temp_c', 0.0):.1f}°C",
        color="#F8FAFC",
        fontsize=11.5,
        fontweight="bold",
    )
    for i, c in enumerate(cpks):
        ax.text(i, c + max(cpks or [1.0]) * 0.02, f"${c:.2f}", ha="center", color="#F8FAFC", fontsize=8.5)
    fig.tight_layout(pad=2.0)
    return fig


def _make_sources_figure(source_rows: list[dict[str, Any]]) -> Figure:
    fig = Figure(figsize=(11.0, 6.2), facecolor="#0F172A")
    ax = fig.add_axes([0.04, 0.05, 0.92, 0.90], facecolor="#0F172A")
    ax.axis("off")
    ax.text(0.0, 0.93, "Scientific Literature & Authoritative Model Provenance", fontsize=17, fontweight="bold", color="#F8FAFC")
    ax.text(0.0, 0.87, "Primary standards, NATO STANAGs, UNODA guidelines, and peer-reviewed papers backing this study:", fontsize=10, color="#93C5FD")

    rows_txt = [
        [
            r["source_id"],
            f"{r['title'][:58]}{'...' if len(r['title']) > 58 else ''}",
            f"{r['authors'][:28]} ({r.get('year') or 'n/a'})",
            r["doi"] if r["doi"] else r["type"][:22],
        ]
        for r in source_rows[:12]
    ]
    if rows_txt:
        table = ax.table(
            cellText=rows_txt,
            colLabels=["ID", "Reference Title", "Author / Authority", "DOI / Type"],
            loc="center",
            bbox=[0.0, 0.05, 1.0, 0.76],
        )
        table.auto_set_font_size(False)
        table.set_fontsize(8.0)
        for (row_idx, _col_idx), cell in table.get_celld().items():
            if row_idx == 0:
                cell.set_facecolor("#1E3A8A")
                cell.set_text_props(color="#FFFFFF", fontweight="bold")
            else:
                cell.set_facecolor("#1E293B" if row_idx % 2 == 1 else "#0F172A")
                cell.set_text_props(color="#E2E8F0")
            cell.set_edgecolor("#334155")
    return fig


def _resolve_citations(source_ids: list[str] | None) -> list[dict[str, Any]]:
    cat = get_literature_catalog()
    by_id = {r["source_id"]: r for r in cat}
    chosen_ids = source_ids or ["S01", "S13", "S16", "S26", "S27", "S32", "S41", "S43", "S44", "S49", "S52", "S66"]
    return [by_id[s] for s in chosen_ids if s in by_id]


def _collect_briefing_sections(
    title: str,
    subtitle: str,
    ab_result: dict[str, Any] | None = None,
    site_result: dict[str, Any] | None = None,
    tornado_result: dict[str, Any] | None = None,
    logistics_result: dict[str, Any] | None = None,
    raid_result: dict[str, Any] | None = None,
    simulator_summary: dict[str, Any] | None = None,
    source_ids: list[str] | None = None,
) -> tuple[list[tuple[str, str, str]], list[tuple[str, Figure]], list[dict[str, Any]]]:
    kpis: list[tuple[str, str, str]] = []
    if simulator_summary:
        disp = simulator_summary.get("dispersion", simulator_summary)
        eff = simulator_summary.get("effectiveness", {})
        if "cep_m" in disp:
            kpis.append(("Artillery / Core Sim", "Mean Range / CEP50", f"{disp.get('mean_range_m', 0.0):.1f} m / {disp.get('cep_m', 0.0):.1f} m"))
        if "salvo_pk_mean" in eff:
            kpis.append(("Artillery / Core Sim", "Correlated Salvo Pk", f"{eff.get('salvo_pk_mean', 0.0):.3f}"))
    if ab_result:
        ab_sm = ab_result.get("summary", {})
        win_lbl = ab_sm.get("winner_label", ab_result.get("winner_name", "N/A"))
        win_mei = ab_sm.get("winner_mei", 0.0)
        kpis.append(("C-UAS Comparator (M10)", "Leading Turret Architecture", f"{win_lbl} (MEI {win_mei:.1f})"))
    if site_result:
        ssm = site_result.get("summary", {})
        kpis.append(("Site Defense (M7)", "360° Perimeter Coverage", f"{ssm.get('perimeter_coverage_pct', 0.0):.1f}% (Blind: {ssm.get('blind_spot_pct', 0.0):.1f}%)"))
        kpis.append(("Site Defense (M7)", "Zero-Breach Stop Rate", f"{ssm.get('site_zero_breach_pct', 0.0):.1f}%"))
    if raid_result:
        rsm = raid_result.get("summary", {})
        kpis.append(("Unified 3D Raid (M12)", "Swarm Kill Rate / Zero-Breach", f"{rsm.get('mean_kill_rate_pct', 0.0):.1f}% / {rsm.get('zero_breach_pct', 0.0):.1f}%"))
        kpis.append(("Unified 3D Raid (M12)", "Cost per Kill / Peak Barrel Temp", f"${rsm.get('cost_per_kill_usd', 0.0):.2f} / {rsm.get('peak_barrel_temp_c', 0.0):.1f}°C"))
    if logistics_result:
        lsm = logistics_result.get("summary", {})
        kpis.append(("Sustained Logistics (M9)", "Peak Temp / $/Kill", f"{lsm.get('peak_barrel_temp_c', 0.0):.1f}°C / ${lsm.get('mean_cost_per_kill_usd', 0.0):.2f}"))
    if tornado_result:
        tsm = tornado_result.get("summary", {})
        kpis.append(("Sensitivity Tornado (M11)", "#1 Bottleneck Driver", f"{tsm.get('top_driver', 'N/A')} (Swing {tsm.get('top_swing', 0.0):.1f})"))
    if not kpis:
        kpis.append(("Workbench Baseline", "Status", "Ready — execute modules to populate quantitative KPIs"))

    figs: list[tuple[str, Figure]] = [
        ("Executive Summary & KPI Scorecard", _make_cover_figure(title, subtitle, kpis))
    ]
    if ab_result and (ab_result.get("scorecard") or ab_result.get("candidates")):
        figs.append(("A/B Turret Architecture Scorecard", _make_ab_radar_chart_fig(ab_result)))
    if (site_result is not None) or (raid_result is not None):
        figs.append(("Multi-Turret Site Defense & Cooperative Raid", _make_site_or_raid_chart_fig(site_result, raid_result)))
    if tornado_result and tornado_result.get("rows"):
        figs.append(("Sensitivity & Engineering Bottleneck Tornado", _make_tornado_chart_fig(tornado_result)))
    if logistics_result and logistics_result.get("economics_comparison"):
        figs.append(("Sustained Logistics & Payload Economics", _make_logistics_chart_fig(logistics_result)))

    citations = _resolve_citations(source_ids)
    figs.append(("Scientific Literature & Provenance Citations", _make_sources_figure(citations)))
    return kpis, figs, citations


def generate_executive_briefing_pdf(
    title: str = "Ballistics & C-UAS Engineering Executive Briefing",
    subtitle: str = "Stochastic Monte Carlo Trade-Study & Vulnerability Assessment",
    ab_result: dict[str, Any] | None = None,
    site_result: dict[str, Any] | None = None,
    tornado_result: dict[str, Any] | None = None,
    logistics_result: dict[str, Any] | None = None,
    raid_result: dict[str, Any] | None = None,
    simulator_summary: dict[str, Any] | None = None,
    source_ids: list[str] | None = None,
) -> bytes:
    """Render multi-page landscape executive PDF briefing into raw bytes."""
    _, figs, _ = _collect_briefing_sections(
        title=title,
        subtitle=subtitle,
        ab_result=ab_result,
        site_result=site_result,
        tornado_result=tornado_result,
        logistics_result=logistics_result,
        raid_result=raid_result,
        simulator_summary=simulator_summary,
        source_ids=source_ids,
    )
    buf = io.BytesIO()
    with PdfPages(buf) as pdf:
        for _, fig in figs:
            pdf.savefig(fig, facecolor=fig.get_facecolor())
    return buf.getvalue()


def generate_executive_briefing_pptx(
    title: str = "Ballistics & C-UAS Engineering Executive Briefing",
    subtitle: str = "Stochastic Monte Carlo Trade-Study & Vulnerability Assessment",
    ab_result: dict[str, Any] | None = None,
    site_result: dict[str, Any] | None = None,
    tornado_result: dict[str, Any] | None = None,
    logistics_result: dict[str, Any] | None = None,
    raid_result: dict[str, Any] | None = None,
    simulator_summary: dict[str, Any] | None = None,
    source_ids: list[str] | None = None,
) -> bytes:
    """Build native 16:9 widescreen PowerPoint (.pptx) deck with charts, tables & citations."""
    kpis, figs, citations = _collect_briefing_sections(
        title=title,
        subtitle=subtitle,
        ab_result=ab_result,
        site_result=site_result,
        tornado_result=tornado_result,
        logistics_result=logistics_result,
        raid_result=raid_result,
        simulator_summary=simulator_summary,
        source_ids=source_ids,
    )
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank_layout = prs.slide_layouts[6]

    def _add_header_slide(header_text: str, sub_text: str) -> Any:
        slide = prs.slides.add_slide(blank_layout)
        bg = slide.background.fill
        bg.solid()
        bg.fore_color.rgb = RGBColor(15, 23, 42)
        tb = slide.shapes.add_textbox(Inches(0.55), Inches(0.28), Inches(12.2), Inches(0.95))
        tf = tb.text_frame
        tf.word_wrap = True
        p0 = tf.paragraphs[0]
        p0.text = header_text
        p0.font.size = Pt(22)
        p0.font.bold = True
        p0.font.color.rgb = RGBColor(248, 250, 252)
        p1 = tf.add_paragraph()
        p1.text = sub_text
        p1.font.size = Pt(11)
        p1.font.color.rgb = RGBColor(147, 197, 253)
        return slide

    # Slide 1: Cover + Native KPI Scorecard Table
    s_cov = _add_header_slide(title, f"{subtitle} | ammo-mc v{__version__}")
    gov_box = s_cov.shapes.add_textbox(Inches(0.55), Inches(1.25), Inches(12.2), Inches(0.60))
    gov_tf = gov_box.text_frame
    gov_tf.word_wrap = True
    gp = gov_tf.paragraphs[0]
    gp.text = f"GOVERNANCE: {USE_LIMITATION_NOTICE}"
    gp.font.size = Pt(10)
    gp.font.color.rgb = RGBColor(253, 230, 138)

    n_k = min(len(kpis), 10)
    tbl_shape = s_cov.shapes.add_table(n_k + 1, 3, Inches(0.55), Inches(1.95), Inches(12.2), Inches(4.8))
