    simulator_summary: dict[str, Any] | None = None,
    source_ids: list[str] | None = None,
    adversarial_result: dict[str, Any] | None = None,
    calibration_result: dict[str, Any] | None = None,
    vv_result: dict[str, Any] | None = None,
