        tf = tb.text_frame
        tf.word_wrap = True
        p0 = tf.paragraphs[0]
        p0.text = header_text
        p0.font.size = Pt(22)
        p0.font.bold = True
        p0.font.color.rgb = RGBColor(248, 250, 252)
        p1 = tf.add_paragraph()
        p1.text = sub_text
        p1.font.size = Pt(11)
        p1.font.color.rgb = RGBColor(147, 197, 253)
        return slide

