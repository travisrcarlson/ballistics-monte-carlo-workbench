"""Presentation-Grade Multi-Page PDF & 16:9 PowerPoint (.pptx) Executive Briefing Generator.

Thread-safe, zero-Kaleido implementation rendering charts via Matplotlib FigureCanvasAgg
and native tables/slides via PdfPages and `python-pptx`.
"""

